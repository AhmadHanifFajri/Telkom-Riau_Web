<script>
  (function () {
    const grid = document.getElementById('iklanGrid');
    const modal = document.getElementById('lightbox');
    const imgEl = document.getElementById('lightboxImage');
    const btnClose = modal.querySelector('.lightbox-close');

    // Simpan urutan semua trigger untuk navigasi keyboard
    const triggers = Array.from(document.querySelectorAll('.lightbox-trigger'));
    let currentIndex = -1;

    function openLightbox(index) {
      const trigger = triggers[index];
      if (!trigger) return;

      const fullSrc = trigger.getAttribute('data-full') || trigger.getAttribute('src');
      const altText = trigger.getAttribute('alt') || 'Gambar';
      imgEl.src = fullSrc;
      imgEl.alt = altText;
      currentIndex = index;

      modal.classList.add('is-open');
      modal.setAttribute('aria-hidden', 'false');

      // mencegah scroll body di iOS/Android
      document.documentElement.style.overflow = 'hidden';
    }

    function closeLightbox() {
      modal.classList.remove('is-open');
      modal.setAttribute('aria-hidden', 'true');
      imgEl.src = '';
      imgEl.alt = '';
      document.documentElement.style.overflow = '';
      currentIndex = -1;
    }

    function showNext(delta) {
      if (currentIndex < 0) return;
      const total = triggers.length;
      const nextIndex = (currentIndex + delta + total) % total;
      openLightbox(nextIndex);
    }

    // Delegasi klik pada grid
    grid.addEventListener('click', function (e) {
      const target = e.target.closest('.lightbox-trigger');
      if (!target) return;
      const index = triggers.indexOf(target);
      if (index > -1) openLightbox(index);
    });

    // Tutup lewat tombol
    btnClose.addEventListener('click', closeLightbox);

    // Tutup jika klik di luar gambar
    modal.addEventListener('click', function (e) {
      const clickedInside = e.target.closest('.lightbox-inner');
      if (!clickedInside) closeLightbox();
    });

    // Keyboard: Esc untuk tutup, panah kiri/kanan untuk navigasi
    document.addEventListener('keydown', function (e) {
      if (!modal.classList.contains('is-open')) return;

      if (e.key === 'Escape') {
        e.preventDefault();
        closeLightbox();
      } else if (e.key === 'ArrowRight') {
        e.preventDefault();
        showNext(1);
      } else if (e.key === 'ArrowLeft') {
        e.preventDefault();
        showNext(-1);
      }
    });

    // (Opsional) Swipe sederhana untuk mobile
    let touchStartX = 0;
    modal.addEventListener('touchstart', function (e) {
      touchStartX = e.changedTouches[0].clientX;
    }, {passive: true});

    modal.addEventListener('touchend', function (e) {
      const dx = e.changedTouches[0].clientX - touchStartX;
      const threshold = 40; // piksel
      if (Math.abs(dx) > threshold) {
        showNext(dx < 0 ? 1 : -1);
      }
    }, {passive: true});
  })();
</script>

