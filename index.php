    <script>
        // Script untuk auto-scroll artikel
         const artikelCarouselWrapper = document.querySelector('.artikel-carousel-wrapper');
  const artikelGrid = document.querySelector('.artikel-grid');

  let autoScrollIntervalArtikel;

  function getMaxScrollLeft(el) {
    return el.scrollWidth - el.clientWidth;
  }

  function startContinuousScrollArtikel() {
    if (autoScrollIntervalArtikel) clearInterval(autoScrollIntervalArtikel);
    if (!artikelCarouselWrapper || !artikelGrid) return;

    // Jika konten tidak lebih lebar dari viewport, tidak perlu auto-scroll
    const max = getMaxScrollLeft(artikelCarouselWrapper);
    if (max <= 0) return;

    const step = 1;           // px per tick
    const intervalMs = 15;    // kecepatan

    autoScrollIntervalArtikel = setInterval(() => {
      const max = getMaxScrollLeft(artikelCarouselWrapper);

      if (artikelCarouselWrapper.scrollLeft >= max - 1) {
        // reset ke awal ketika sudah mentok
        artikelCarouselWrapper.scrollLeft = 0;
      } else {
        artikelCarouselWrapper.scrollLeft += step;
      }
    }, intervalMs);
  }

  function stopContinuousScrollArtikel() {
    clearInterval(autoScrollIntervalArtikel);
    autoScrollIntervalArtikel = null;
  }

  // Mulai saat DOM siap
  document.addEventListener('DOMContentLoaded', startContinuousScrollArtikel);

  // (Opsional) Pause saat hover agar user bisa klik
  if (artikelCarouselWrapper) {
    artikelCarouselWrapper.addEventListener('mouseenter', stopContinuousScrollArtikel);
    artikelCarouselWrapper.addEventListener('mouseleave', startContinuousScrollArtikel);
  }

document.addEventListener('DOMContentLoaded', function () {
        const counters = document.querySelectorAll('.stat-number');
        const speed = 100; // Makin kecil makin cepat (default: 100)

        counters.forEach(counter => {
            const updateCount = () => {
                const target = +counter.getAttribute('data-target');
                const count = +counter.innerText;

                const increment = target / speed;

                if (count < target) {
                    counter.innerText = Math.ceil(count + increment);
                    setTimeout(updateCount, 15);
                } else {
                    counter.innerText = target;
                }
            };

            updateCount();
        });
    });


    </script>

