    <script>
        function scrollArtikel(direction) {
            const wrapper = document.querySelector('.artikel-carousel-wrapper');
            const scrollAmount = 320;

            if (wrapper) {
                if (direction === 'left') {
                    wrapper.scrollBy({
                        left: -scrollAmount,
                        behavior: 'smooth'
                    });
                } else {
                    wrapper.scrollBy({
                        left: scrollAmount,
                        behavior: 'smooth'
                    });
                }
            }
        }

        const modal = document.getElementById("teamMemberModal");
        const openModalButtons = document.querySelectorAll(".open-member-modal");
        const closeSpan = document.querySelector(".modal-content .close-button");
        const closeModalButton = document.querySelector(".close-modal-button");

        const modalImage = document.getElementById("modalImage");
        const modalName = document.getElementById("modalName");
        const modalTitle = document.getElementById("modalTitle");
        const modalEducationUniv = document.getElementById("modalEducationUniv");
        const modalEducationMajor = document.getElementById("modalEducationMajor");

        openModalButtons.forEach(button => {
            button.onclick = function(event) {
                event.preventDefault();

                const teamCard = this.closest('.team-card'); 
                
                modalImage.src = teamCard.dataset.image;
                modalImage.alt = teamCard.dataset.name + " Image";
                modalName.textContent = teamCard.dataset.name;
                modalTitle.textContent = teamCard.dataset.title;
                modalEducationUniv.textContent = teamCard.dataset.educationUniv;
                modalEducationMajor.textContent = teamCard.dataset.educationMajor;

                modal.style.display = "flex"; // Tampilkan modal
            };
        });

        function closeTeamModal() {
            modal.style.display = "none";
            modalImage.src = "";
            modalImage.alt = "";
            modalName.textContent = "";
            modalTitle.textContent = "";
            modalEducationUniv.textContent = "";
            modalEducationMajor.textContent = "";
        }

        closeSpan.onclick = closeTeamModal;
        closeModalButton.onclick = closeTeamModal;

        window.onclick = function(event) {
            if (event.target == modal) {
                closeTeamModal();
            }
        };
    </script>

